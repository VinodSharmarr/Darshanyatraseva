/* पर्व पोस्ट का कैप्शन, तारीख़ और नाम भरकर बनता है */
function parvCaption(names, dateStr, tithi, dhamKey) {
  const d = dhamKey ? DHAM[dhamKey] : null;
  const lines = [
    '🪔 ' + names.join(', '),
    '📅 ' + dateStr,
    '🗓️ ' + tithi,
    ''
  ];
  if (d && d.book) {
    lines.push('इस तिथि पर ' + d.name + ' के दर्शन का मन हो तो सीट अभी पूछ लीजिए। पर्व वाले दिनों की सीट सबसे पहले भरती है।');
  } else if (d) {
    lines.push('इस पर्व की कथा और महत्व हमारी वेबसाइट के कथा वाले पन्ने पर पढ़िए।');
  } else {
    lines.push('इस तिथि पर यात्रा का मन हो तो सीट अभी पूछ लीजिए। पर्व वाले दिनों की सीट सबसे पहले भरती है।');
  }
  lines.push('', '🗓️ पूरा पंचांग: ' + FACTS.site + '/panchang');
  return lines.join('\n');
}

